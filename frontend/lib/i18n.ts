interface LanguageContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
  isRTL: boolean;
}

const LanguageContext = createContext<LanguageContextValue>({
  lang: 'ku',
  setLang: () => {},
  t: (key) => key,
  isRTL: true,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('ku');

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY).then((saved) => {
      if (saved === 'ku' || saved === 'ar' || saved === 'en') {
        setLangState(saved);
      }
    });
  }, []);

  const setLang = (newLang: Lang) => {
    console.log('[i18n] Language changed to:', newLang);
    setLangState(newLang);
    AsyncStorage.setItem(STORAGE_KEY, newLang);
  };

  const t = (key: string): string => {
    return translations[lang]?.[key] ?? translations['ku']?.[key] ?? key;
  };

  const isRTL = lang === 'ku' || lang === 'ar';

  const value: LanguageContextValue = { lang, setLang, t, isRTL };

  return React.createElement(LanguageContext.Provider, { value }, children);
}

export function useLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}
